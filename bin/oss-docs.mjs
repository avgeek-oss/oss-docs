#!/usr/bin/env node
import { readFile, writeFile, mkdir, realpath } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { format } from "prettier";
import { defineSite } from "../src/index.mjs";

const packageRoot = fileURLToPath(new URL("../", import.meta.url));
function onPrimary(hex) {
  const channels = [1, 3, 5].map((index) => {
    const value = Number.parseInt(hex.slice(index, index + 2), 16) / 255;
    return value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4;
  });
  const luminance =
    channels[0] * 0.2126 + channels[1] * 0.7152 + channels[2] * 0.0722;
  return (luminance + 0.05) / 0.05 >= 1.05 / (luminance + 0.05)
    ? "#171717"
    : "#ffffff";
}

export async function syncSite({ config, dir, check = false }) {
  const site = defineSite(JSON.parse(await readFile(resolve(config), "utf8")));
  const { version } = JSON.parse(
    await readFile(resolve(packageRoot, "package.json"), "utf8"),
  );
  const outputs = new Map([
    ["docs.json", JSON.stringify(site, null, 2) + "\n"],
  ]);
  const css = await readFile(resolve(packageRoot, "assets/layout.css"), "utf8");
  const brand = site.colors;
  for (const color of Object.values(brand)) {
    if (!/^#[a-f\d]{6}$/i.test(color))
      throw new Error("Brand colors must be six-digit hex values");
  }
  const theme = `:root { --oss-primary: ${brand.primary}; --oss-primary-hover: color-mix(in oklch, var(--oss-primary) 92%, black); --oss-on-primary: ${onPrimary(brand.primary)}; --oss-heading-accent: ${brand.light}; }\n.dark { --oss-primary: ${brand.dark}; --oss-primary-hover: color-mix(in oklch, var(--oss-primary) 90%, white); --oss-on-primary: ${onPrimary(brand.dark)}; --oss-heading-accent: ${brand.dark}; }\n`;
  outputs.set(
    "oss-docs.css",
    `/* Generated by @avgeek-oss/docs ${version}; run docs:sync to update. */\n${theme}${css}`,
  );
  const header = await readFile(
    resolve(packageRoot, "assets/header.js"),
    "utf8",
  );
  outputs.set(
    "oss-docs.js",
    header.replace(
      "__OSS_DOCS_SETTINGS__",
      JSON.stringify({ name: site.name }),
    ),
  );
  for (const name of ["homepage", "screenshot"])
    outputs.set(
      `snippets/oss/${name}.jsx`,
      await readFile(resolve(packageRoot, `snippets/${name}.jsx`), "utf8"),
    );
  for (const [name, content] of outputs) {
    outputs.set(
      name,
      await format(content, {
        parser: name.endsWith(".json")
          ? "json"
          : name.endsWith(".css")
            ? "css"
            : "babel",
      }),
    );
  }
  const manifest = {
    package: "@avgeek-oss/docs",
    version,
    files: Object.fromEntries(
      [...outputs].map(([name, content]) => [
        name,
        createHash("sha256").update(content).digest("hex"),
      ]),
    ),
  };
  outputs.set(
    ".oss-docs.json",
    await format(JSON.stringify(manifest), { parser: "json" }),
  );
  const failures = [];
  for (const [name, content] of outputs) {
    const target = resolve(dir, name);
    if (check) {
      let actual;
      try {
        actual = await readFile(target, "utf8");
      } catch (error) {
        if (error.code !== "ENOENT") throw error;
      }
      if (actual !== content) failures.push(name);
    } else {
      await mkdir(dirname(target), { recursive: true });
      await writeFile(target, content);
    }
  }
  if (failures.length)
    throw new Error(
      `Generated documentation differs: ${failures.join(", ")}; run docs:sync`,
    );
  return [...outputs.keys()];
}

if (
  process.argv[1] &&
  (await realpath(resolve(process.argv[1]))) === fileURLToPath(import.meta.url)
) {
  const [command, ...args] = process.argv.slice(2);
  const option = (name) => args[args.indexOf(name) + 1];
  if (
    !["sync", "check"].includes(command) ||
    !args.includes("--config") ||
    !args.includes("--dir")
  ) {
    console.error(
      "Usage: oss-docs <sync|check> --config <site.json> --dir <content directory>",
    );
    process.exitCode = 1;
  } else {
    try {
      await syncSite({
        config: option("--config"),
        dir: option("--dir"),
        check: command === "check",
      });
    } catch (error) {
      console.error(error.message);
      process.exitCode = 1;
    }
  }
}
