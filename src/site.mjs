import { readFile, writeFile, mkdir, rm } from "node:fs/promises";
import { dirname, relative, resolve, sep } from "node:path";
import { createHash } from "node:crypto";
import { format } from "prettier";
import { loadSite } from "./load.mjs";
import { checkContent } from "./content.mjs";

const packageRoot = new URL("../", import.meta.url);
const packageFile = (path) => new URL(path, packageRoot);

function onPrimary(hex) {
  const channels = [1, 3, 5].map((index) => {
    const value = Number.parseInt(hex.slice(index, index + 2), 16) / 255;
    return value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4;
  });
  const luminance =
    channels[0] * 0.2126 + channels[1] * 0.7152 + channels[2] * 0.0722;
  return (luminance + 0.05) / 0.05 >= 1.05 / (luminance + 0.05)
    ? "#171717"
    : "#ffffff";
}

// The footer GitHub social link that gets an "owner/repository" label.
function footerRepository(site) {
  const href = site.footer?.socials?.github;
  if (typeof href !== "string") return null;
  if (!URL.canParse(href))
    throw new Error(`footer.socials.github must be an absolute URL: ${href}`);
  const url = new URL(href);
  const segments = url.pathname.split("/").filter(Boolean);
  if (
    url.protocol !== "https:" ||
    url.hostname !== "github.com" ||
    segments.length !== 2
  )
    return null;
  const label = segments.join("/");
  return { href: `https://github.com/${label}`, label };
}

async function generate({ site, assets }) {
  const { version } = JSON.parse(
    await readFile(packageFile("package.json"), "utf8"),
  );
  const outputs = new Map([
    ["docs.json", JSON.stringify(site, null, 2) + "\n"],
  ]);
  const css = await readFile(packageFile("assets/layout.css"), "utf8");
  const brand = site.colors;
  for (const color of Object.values(brand)) {
    if (!/^#[a-f\d]{6}$/i.test(color))
      throw new Error("Brand colors must be six-digit hex values");
  }
  const theme = `:root { --oss-primary: ${brand.primary}; --oss-primary-hover: color-mix(in oklch, var(--oss-primary) 92%, black); --oss-on-primary: ${onPrimary(brand.primary)}; --oss-heading-accent: ${brand.primary}; }\n.dark { --oss-primary: ${brand.light}; --oss-primary-hover: color-mix(in oklch, var(--oss-primary) 90%, white); --oss-on-primary: ${onPrimary(brand.light)}; --oss-heading-accent: ${brand.light}; }\n`;
  outputs.set(
    "oss-docs.css",
    `/* Generated by @avgeek-oss/mintlify-docs ${version}; run docs:sync to update. */\n${theme}${css}`,
  );
  const header = await readFile(packageFile("assets/header.js"), "utf8");
  outputs.set(
    "oss-docs.js",
    header.replace(
      "__OSS_DOCS_SETTINGS__",
      JSON.stringify({ name: site.name, repository: footerRepository(site) }),
    ),
  );
  for (const name of ["homepage", "screenshot"])
    outputs.set(
      `snippets/oss/${name}.jsx`,
      await readFile(packageFile(`snippets/${name}.jsx`), "utf8"),
    );
  for (const [name, content] of outputs) {
    outputs.set(
      name,
      await format(content, {
        parser: name.endsWith(".json")
          ? "json"
          : name.endsWith(".css")
            ? "css"
            : "babel",
      }),
    );
  }
  for (const asset of assets) {
    try {
      outputs.set(asset.to, await readFile(asset.from));
    } catch (error) {
      if (error.code === "ENOENT")
        throw new Error(`Missing asset source for ${asset.to}: ${asset.from}`);
      throw error;
    }
  }
  const manifest = {
    package: "@avgeek-oss/mintlify-docs",
    version,
    files: Object.fromEntries(
      [...outputs].map(([name, content]) => [
        name,
        createHash("sha256").update(content).digest("hex"),
      ]),
    ),
  };
  outputs.set(
    ".oss-docs.json",
    await format(JSON.stringify(manifest), { parser: "json" }),
  );
  return outputs;
}

function inside(dir, name) {
  const target = resolve(dir, name);
  const path = relative(dir, target);
  return path && !path.startsWith(`..${sep}`) && path !== ".." ? target : null;
}

// Files the committed manifest lists that this configuration no longer generates.
async function previouslyGenerated(dir, outputs) {
  let manifest;
  try {
    manifest = JSON.parse(
      await readFile(resolve(dir, ".oss-docs.json"), "utf8"),
    );
  } catch (error) {
    if (error.code === "ENOENT" || error instanceof SyntaxError) return [];
    throw error;
  }
  if (manifest?.package !== "@avgeek-oss/mintlify-docs") return [];
  return Object.keys(manifest.files ?? {}).filter(
    (name) => !outputs.has(name) && inside(dir, name),
  );
}

async function readOptional(path) {
  try {
    return await readFile(path);
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
}

async function driftProblems(loaded, dir) {
  const outputs = await generate(loaded);
  const differs = [];
  for (const [name, content] of outputs) {
    const actual = await readOptional(resolve(dir, name));
    if (!actual?.equals(Buffer.from(content))) differs.push(name);
  }
  const stale = [];
  for (const name of await previouslyGenerated(dir, outputs))
    if ((await readOptional(resolve(dir, name))) !== null) stale.push(name);
  return { outputs, differs, stale };
}

function driftMessage(differs, stale) {
  return [
    differs.length &&
      `Generated documentation differs: ${differs.join(", ")}; run docs:sync`,
    stale.length &&
      `No longer generated: ${stale.join(", ")}; run docs:sync to remove`,
  ].filter(Boolean);
}

export class SiteCheckError extends Error {
  constructor(problems) {
    super(problems.join("\n"));
    this.name = "SiteCheckError";
    this.problems = problems;
  }
}

export async function syncSite({ config, dir, check = false }) {
  const loaded = await loadSite(config);
  const target = resolve(dir);
  if (check) {
    const { outputs, differs, stale } = await driftProblems(loaded, target);
    if (differs.length || stale.length)
      throw new SiteCheckError(driftMessage(differs, stale));
    return [...outputs.keys()];
  }
  const outputs = await generate(loaded);
  const stale = await previouslyGenerated(target, outputs);
  for (const [name, content] of outputs) {
    const path = resolve(target, name);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
  }
  for (const name of stale) await rm(resolve(target, name), { force: true });
  return [...outputs.keys()];
}

// Checks generated files byte for byte and, with `content`, the pages,
// links, assets and screenshots they publish. Every problem is reported.
export async function checkSite({ config, dir, content = false }) {
  const loaded = await loadSite(config);
  const target = resolve(dir);
  const { outputs, differs, stale } = await driftProblems(loaded, target);
  const problems = driftMessage(differs, stale);
  const report = content ? await checkContent({ loaded, dir: target }) : null;
  if (report) problems.push(...report.problems);
  if (problems.length) throw new SiteCheckError(problems);
  return {
    files: [...outputs.keys()],
    ...(report && {
      pages: report.pages,
      links: report.links,
      images: report.images,
    }),
  };
}
